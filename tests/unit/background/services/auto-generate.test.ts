test("额度用完或密钥不对时停下、告诉页面；之后不再触发，恢复以后照常。别的错误不停", async () => {
  const { auto, started, paused, state } = setup();
  await auto.consider();
  const [first] = started;
  assert.ok(first);
  first.hooks.failed(Object.assign(new Error("服务出错"), { status: 500 }));
  first.hooks.failed(Object.assign(new Error("限流"), { status: 429 }));
  assert.ok(await stillFalse(() => paused.length > 0));
  first.hooks.failed(Object.assign(new Error("额度用完"), { status: 429, quotaExhausted: true }));
  assert.ok(await until(async () => (await auto.paused()) === "quota"));
  first.hooks.failed(Object.assign(new Error("密钥不对"), { status: 401 }));
  state.tabs.set(WINDOW, { id: 4, windowId: WINDOW, url: videoPageUrl(OTHER_ID) });
  assert.deepEqual(await auto.consider(), { skipped: "paused" });
  assert.deepEqual(paused, ["quota"], "已经停着，再报一次不重复告诉页面");

  await auto.resume();
  assert.deepEqual(paused, ["quota", null]);
  assert.equal(await auto.paused(), null);
  await auto.resume();
  assert.deepEqual(paused, ["quota", null], "没停着时恢复什么都不做");
  // 恢复以后照常：前一个收了尾，前台的那个接着生成。
  first.finish();
  assert.ok(await until(() => started.length === 2));
  assert.equal(started[1]?.video, OTHER);
});

test("哪些错误算额度用完、哪些算密钥不对", () => {
  assert.equal(pauseReasonOf({ status: 429, quotaExhausted: true }), "quota");
  assert.equal(pauseReasonOf({ status: 402 }), "quota");
  for (const error of [{ status: 401 }, { status: 403 }, { code: "INVALID_AI_KEY" }, { code: "ANTHROPIC_WORKSPACE_REQUIRED" }]) assert.equal(pauseReasonOf(error), "key");
  for (const error of [{ status: 429 }, { status: 500 }, { code: "TASK_CANCELED" }, { code: "AI_NETWORK_ERROR" }, null, "error"]) assert.equal(pauseReasonOf(error), null);
});

