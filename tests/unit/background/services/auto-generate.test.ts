const MIN_SEC = 10 * 60;
const START = 1_800_000_000_000;

/** B 站按真实的地址规则认；另一个站的地址规则还没有，这里认测试自造的地址。 */
const parseWatchUrl = (url: string): VideoRef | null =>
  siteRules.bilibili?.parseWatchUrl(url) ?? (url.startsWith(TUBE_ORIGIN) ? { platform: "youtube", videoId: "tube-sample" } : null);

const CURRENT = currentStamp(DATA_CONSENT_TABLE);

interface Setup {
  readonly enabled?: boolean;
  readonly on?: boolean;
  readonly minSec?: number;
  readonly consent?: { readonly version: number; readonly fingerprint: string };
  readonly configReady?: boolean;
  readonly overview?: boolean;
  readonly known?: number | null;
  readonly read?: { readonly durationSec: number } | null;
  readonly ledger?: unknown;
  readonly launch?: "joined" | "conflict";
}

/** 测试决定自动任务什么时候收尾；没收尾的算在跑。 */
interface Run {
  readonly video: VideoKey;
  readonly hooks: AutoHooks;
  settled: boolean;
  finish(): void;
}

function setup(options: Setup = {}) {
  const timers = manualTimers(START);
  const storage = memoryStorage(options.ledger === undefined ? {} : { [AUTO_LEDGER_KEY]: options.ledger });
  const guard = createClearGuard();
  const started: Run[] = [];
  const paused: (AutoPauseReason | null)[] = [];
  const calls = { windows: 0, tabs: [] as number[], reads: 0, known: 0 };
  const state = {
    focused: WINDOW as number | null,
    tabs: new Map<number, AutoTab>([[WINDOW, { id: 3, windowId: WINDOW, url: videoPageUrl(SAMPLE_ID) }]]),
    on: options.on ?? true,
    read: options.read === undefined ? { durationSec: LONG } : options.read,
    onRead: null as (() => void) | null,
  };
  const deps: AutoGenerateDeps = {
    settings: async () => ({ enabled: options.enabled ?? true, on: state.on, minSec: options.minSec ?? MIN_SEC, consent: options.consent ?? CURRENT }),
    focusedWindow: async () => {
      calls.windows += 1;
      return state.focused;
    },
    activeTab: async (windowId) => {
      calls.tabs.push(windowId);
      return state.tabs.get(windowId) ?? null;
    },
    parseWatchUrl,
    configReady: async () => options.configReady ?? true,
    running: () => started.filter((run) => !run.settled).length,
    hasOverview: async () => options.overview ?? false,
    knownDuration: async () => {
      calls.known += 1;
      return options.known ?? null;
    },
    readTranscript: async () => {
      calls.reads += 1;
      state.onRead?.();
      return state.read;
    },
    start: async (_ref, video, hooks): Promise<AutoLaunch> => {
      if (options.launch) return { skipped: options.launch };
      let finish = (): void => {};
      const done = new Promise<void>((resolve) => (finish = resolve));
      const run: Run = {
        video,
        hooks,
        settled: false,
        finish() {
          run.settled = true;
          finish();
        },
      };
      started.push(run);
      return { done };
    },
    storage,
    guard,
    now: timers.now,
    onPause: (reason) => void paused.push(reason),
    log: { warn() {}, error() {} },
  };
  const auto = createAutoGenerate(deps);
  const ledger = () => parseLedger(storage.data[AUTO_LEDGER_KEY], timers.now());
  return { auto, timers, storage, guard, started, paused, calls, state, ledger };
}

test("确认启用之前、开关关着时，不问窗口和标签页、不读地址，也不取字幕", async () => {
  for (const options of [{ enabled: false }, { on: false }] satisfies Setup[]) {
    const { auto, started, calls } = setup(options);
    assert.deepEqual(await auto.consider(), { skipped: "on" in options ? "switch-off" : "not-enabled" });
    assert.deepEqual(calls, { windows: 0, tabs: [], reads: 0, known: 0 }, JSON.stringify(options));
    assert.deepEqual(started, []);
  }
});

test("只看获得焦点的窗口里的活动标签页：焦点不在 Chrome 时不触发，别的窗口里的活动标签页不问", async () => {
  const { auto, state, calls, started } = setup();
  state.focused = null;
  assert.deepEqual(await auto.consider(), { skipped: "not-focused" });
  assert.deepEqual(calls.tabs, []);

  // 别的窗口前台是长视频，获得焦点的窗口前台不是视频页。
  state.focused = WINDOW;
  state.tabs.set(WINDOW, { id: 3, windowId: WINDOW, url: "https://www.bilibili.com/" });
  state.tabs.set(WINDOW + 1, { id: 4, windowId: WINDOW + 1, url: videoPageUrl(OTHER_ID) });
  assert.deepEqual(await auto.consider(), { skipped: "not-video" });
  assert.deepEqual(calls.tabs, [WINDOW]);
  assert.equal(calls.reads, 0);
  assert.deepEqual(started, []);
});

