// 打开 B 站视频就生成的闸门骨架：用替身事件跑完每道闸门。确认前、开关关着时不读标签页地址，
// 后台窗口里的活动标签页不触发，YouTube 不取字幕不记尝试，同意里没有自动发送就不发，额度满了不发，
// 尝试在模型请求真正发出时才记。
import assert from "node:assert/strict";
import { test } from "node:test";
import { AUTO_SEND_TRIGGER, AUTO_WINDOW_LIMIT, AUTO_WINDOW_MS, createAutoGenerate, type AutoAttempt, type AutoFeature, type AutoGenerateDeps, type AutoTab } from "../../../../src/background/services/auto-generate.ts";
import { createClearGuard } from "../../../../src/core/clear-guard.ts";
import { currentStamp, DATA_CONSENT_TABLE, type DataConsentKind, type NoticeTable } from "../../../../src/core/consent.ts";
import { fail } from "../../../../src/core/errors.ts";
import { videoKey, type VideoRef } from "../../../../src/core/video-ref.ts";
import { AUTO_LEDGER_KEY } from "../../../../src/shared/names.ts";
import type { TranscriptReply } from "../../../../src/shared/messages/transcript.ts";
import { siteRules } from "../../../../src/sites/rules.ts";
import { videoPageUrl } from "../../../helpers/bilibili-pages.ts";
import { TUBE_ORIGIN, tubeUrl } from "../../../helpers/chrome.ts";
import { nextTurn } from "../../../helpers/deferred.ts";
import { SAMPLE_ID } from "../../../helpers/fake-site-service.ts";
import { manualTimers } from "../../../helpers/manual-timers.ts";
import { memoryStorage } from "../../../helpers/memory-storage.ts";
import { transcriptView } from "../../../helpers/translate-service.ts";
import { until } from "../../../helpers/wait-until.ts";

const REF: VideoRef = { platform: "bilibili", videoId: SAMPLE_ID, segment: 1 };
const VIDEO = videoKey(REF);
const WINDOW = 7;

/** 第 11 步会加的那一版：数据同意里写了打开视频就自动发送。 */
const WITH_AUTO: NoticeTable<DataConsentKind> = [...DATA_CONSENT_TABLE, { version: DATA_CONSENT_TABLE.length + 1, items: [{ ...AUTO_SEND_TRIGGER, text: "打开视频时自动发送" }] }];
const agreed = (table: NoticeTable<DataConsentKind>) => {
  const { version, fingerprint } = currentStamp(table);
  return { version, fingerprint };
};

/** 记下读过哪些字段的标签页：用来证明某几道闸门之前没读地址。 */
function watchedTab(tab: AutoTab, reads: string[]): AutoTab {
  return new Proxy(tab, {
    get(target, key, receiver) {
      reads.push(String(key));
      return Reflect.get(target, key, receiver);
    },
  });
}

/** B 站按真实的地址规则认；另一个站的地址规则第 10 步才有，这里认测试自造的地址。 */
const parseWatchUrl = (url: string): VideoRef | null =>
  siteRules.bilibili?.parseWatchUrl(url) ?? (url.startsWith(TUBE_ORIGIN) ? { platform: "youtube", videoId: "tube-sample" } : null);

const tabOn = (url: string, overrides: Partial<AutoTab> = {}): AutoTab => ({ id: 3, windowId: WINDOW, active: true, url, ...overrides });

interface Setup {
  readonly enabled?: boolean;
  readonly switchOn?: boolean;
  readonly table?: NoticeTable<DataConsentKind>;
  readonly consent?: { version: number; fingerprint: string };
  readonly configReady?: boolean;
  readonly running?: number;
  readonly overview?: boolean;
  readonly translated?: boolean;
  readonly reply?: TranscriptReply;
  readonly attempts?: readonly AutoAttempt[];
  /** 发起的任务在发出模型请求之前就失败了：不调 onSend。 */
  readonly failBeforeSend?: boolean;
}

async function setup(options: Setup = {}) {
  const timers = manualTimers(1_800_000_000_000);
  const storage = memoryStorage(options.attempts ? { [AUTO_LEDGER_KEY]: { attempts: options.attempts } } : {});
  const guard = createClearGuard();
  const started: { feature: AutoFeature; ref: VideoRef; onSend: () => void }[] = [];
  const reads = { transcript: 0, focus: 0 };
  const table = options.table ?? WITH_AUTO;
  const reply = options.reply ?? { ok: true as const, value: await transcriptView([{ start: 0, duration: 2, text: "Hello there" }], "en-US", VIDEO) };
  const deps: AutoGenerateDeps = {
    focusedWindow: async () => {
      reads.focus += 1;
      return WINDOW;
    },
    enabled: async () => options.enabled ?? true,
    switchOn: async () => options.switchOn ?? true,
    parseWatchUrl,
    consent: async () => options.consent ?? agreed(table),
    consentTable: table,
    configReady: async () => options.configReady ?? true,
    running: () => options.running ?? 0,
    transcript: async () => {
      reads.transcript += 1;
      return reply;
    },
    hasOverview: async () => options.overview ?? false,
    hasTranslation: async () => options.translated ?? false,
    start: (feature, ref, { onSend }) => {
      started.push({ feature, ref, onSend });
      if (!options.failBeforeSend) onSend();
    },
    storage,
    guard,
    now: timers.now,
    log: { warn() {}, error() {} },
  };
  const auto = createAutoGenerate(deps);
  const ledger = async (): Promise<AutoAttempt[]> => ((await storage.get(AUTO_LEDGER_KEY))[AUTO_LEDGER_KEY] as { attempts: AutoAttempt[] } | undefined)?.attempts ?? [];
  return { auto, deps, timers, storage, guard, started, reads, ledger };
}

test("确认启用之前、开关关着时，不读标签页的地址，也不取字幕", async () => {
  for (const options of [{ enabled: false }, { switchOn: false }]) {
    const { auto, started, reads } = await setup(options);
    const touched: string[] = [];
    const outcome = await auto.consider(watchedTab(tabOn(videoPageUrl(SAMPLE_ID)), touched));
    assert.deepEqual(outcome, { skipped: options.enabled === false ? "not-enabled" : "switch-off" });
    assert.equal(touched.includes("url"), false, JSON.stringify(options));
    assert.equal(reads.transcript, 0);
    assert.deepEqual(started, []);
  }
});

test("没有焦点的窗口里的活动标签页、焦点窗口里的后台标签页都不触发", async () => {
  const { auto, started, reads } = await setup();
  const touched: string[] = [];
  assert.deepEqual(await auto.consider(watchedTab(tabOn(videoPageUrl(SAMPLE_ID), { windowId: WINDOW + 1 }), touched)), { skipped: "not-focused" });
  assert.deepEqual(await auto.consider(watchedTab(tabOn(videoPageUrl(SAMPLE_ID), { active: false }), touched)), { skipped: "not-focused" });
  assert.equal(touched.includes("url"), false);
  assert.equal(reads.transcript, 0);
  assert.deepEqual(started, []);
});

test("YouTube 视频不进这条路径：不取字幕，不记尝试", async () => {
  const { auto, started, reads, ledger } = await setup();
  const outcome = await auto.consider(tabOn(tubeUrl()));
  assert.deepEqual(outcome, { skipped: "site-unsupported" });
  assert.equal(reads.transcript, 0);
  assert.deepEqual(started, []);
  assert.deepEqual(await ledger(), []);
});

test("当前数据同意里没有自动发送：同意了现在这一版也不发", async () => {
  const today = await setup({ table: DATA_CONSENT_TABLE, consent: agreed(DATA_CONSENT_TABLE) });
  assert.deepEqual(await today.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "no-consent" });
  assert.equal(today.reads.transcript, 0);

  const older = await setup({ consent: agreed(DATA_CONSENT_TABLE) });
  assert.deepEqual(await older.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "no-consent" }, "说明加了自动发送、用户还没同意新的那一版");

  const covered = await setup();
  assert.deepEqual(await covered.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "overview", video: VIDEO });
});

test("模型配置不齐不发", async () => {
  const { auto, started, reads } = await setup({ configReady: false });
  assert.deepEqual(await auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "no-config" });
  assert.equal(reads.transcript, 0);
  assert.deepEqual(started, []);
});

test("同时只跑一个；滑动 10 分钟里试满 20 个以后不发，最早的滑出窗口再放行", async () => {
  const busy = await setup({ running: 1 });
  assert.deepEqual(await busy.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "busy" });

  const start = 1_800_000_000_000;
  const attempts = Array.from({ length: AUTO_WINDOW_LIMIT }, (_, index) => ({
    feature: "overview" as const,
    video: videoKey({ platform: "bilibili", videoId: `BV1Sample${String(index).padStart(3, "0")}`, segment: 2 }),
    at: start - AUTO_WINDOW_MS + 60_000 + index,
  }));
  const full = await setup({ attempts });
  assert.deepEqual(await full.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "window-full" });
  assert.equal(full.reads.transcript, 0, "额度满了不为它取字幕");
  full.timers.advance(60_000);
  assert.deepEqual(await full.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "overview", video: VIDEO });
});

test("尝试在模型请求真正发出时才记：发出之前就失败的不算试过，下次还会再试；发出过的不再试", async () => {
  const early = await setup({ failBeforeSend: true });
  assert.deepEqual(await early.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "overview", video: VIDEO });
  assert.deepEqual(await early.ledger(), [], "触发时不记");
  assert.deepEqual(await early.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "overview", video: VIDEO }, "下次照样试");
  early.started[1]?.onSend();
  early.started[1]?.onSend();
  assert.ok(await until(async () => (await early.ledger()).length === 1, 20_000), "真正发出时记一次，重发不重记");
  assert.deepEqual(await early.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "translate", video: VIDEO }, "概览试过了，外文视频接着翻译");
});

test("概览和翻译分开判断：已有概览的外文视频照样自动翻译，中文视频和已经译过的不翻", async () => {
  const foreign = await setup({ overview: true });
  assert.deepEqual(await foreign.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "translate", video: VIDEO });

  const chinese = await setup({ overview: true, reply: { ok: true, value: await transcriptView([{ start: 0, duration: 2, text: "中文字幕" }], "zh-CN", VIDEO) } });
  assert.deepEqual(await chinese.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "nothing-to-do" });

  const done = await setup({ overview: true, translated: true });
  assert.deepEqual(await done.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "nothing-to-do" });
});

test("没有字幕也没有官方总结不自动生成概览；只有官方总结时照样生成", async () => {
  const bare = await setup({ reply: fail("NO_CAPTIONS") });
  assert.deepEqual(await bare.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { skipped: "nothing-to-do" });
  assert.deepEqual(bare.started, []);

  const official: TranscriptReply = { ...fail("NO_CAPTIONS"), official: { status: "ok", summary: "官方总结", outline: [], fingerprint: "f" } };
  const summaryOnly = await setup({ reply: official });
  assert.deepEqual(await summaryOnly.auto.consider(tabOn(videoPageUrl(SAMPLE_ID))), { started: "overview", video: VIDEO });
});

test("清除全部数据之后才发出的：尝试记录不写回", async () => {
  const { auto, started, guard, ledger, storage } = await setup({ failBeforeSend: true });
  await auto.consider(tabOn(videoPageUrl(SAMPLE_ID)));
  await guard.clear("all", () => storage.remove(AUTO_LEDGER_KEY));
  started[0]?.onSend();
  for (let turn = 0; turn < 5; turn += 1) await nextTurn();
  assert.deepEqual(await ledger(), []);
});
