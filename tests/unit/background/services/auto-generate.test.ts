test("后台被回收以后：读到过的时长、读不成的、整批停下都还记着，开着的标签页不再读一遍", async () => {
  // 短视频：轻量读取读过一次。
  const short = setup({ light: 5 * 60 });
  assert.deepEqual(await short.auto.consider(), { skipped: "short" });
  assert.ok(await until(async () => short.ledger().durations?.[VIDEO] === 5 * 60));
  assert.deepEqual(await short.restarted().consider(), { skipped: "short" });
  assert.equal(short.calls.light.length, 1, "回收以后不再读");

  // 在后台读不成字幕的：这次会话不再读；到了前台再试。
  const missing = setup({ known: LONG });
  missing.state.front = null;
  missing.state.read = null;
  assert.deepEqual(await missing.auto.consider(), { skipped: "no-captions" });
  assert.ok(await until(async () => missing.ledger().missedBehind?.includes(VIDEO) === true));
  missing.timers.advance(AUTO_RETRY_MS * 3);
  const later = missing.restarted();
  assert.deepEqual(await later.consider(), { skipped: "unavailable" }, "过多久都不再为后台的它读");
  assert.equal(missing.calls.reads.length, 1);
  missing.state.front = FRONT;
  missing.state.read = { durationSec: LONG };
  assert.deepEqual(await later.consider(), { started: VIDEO }, "到了前台再试一次");

  // 在前台读不成的：冷却 10 分钟，回收以后也记着。
  const front = setup({ known: LONG, read: null });
  assert.deepEqual(await front.auto.consider(), { skipped: "no-captions" });
  assert.ok(await until(async () => (front.ledger().unavailable?.[VIDEO] ?? 0) > START));
  assert.deepEqual(await front.restarted().consider(), { skipped: "unavailable" });

  // 整批停下：回收以后照样停着，到点才接着。
  const stopped = setup({ light: "stop" });
  assert.deepEqual(await stopped.auto.consider(), { skipped: "platform-stopped" });
  assert.ok(await until(async () => (stopped.ledger().stoppedUntil ?? 0) > START));
  assert.deepEqual(await stopped.restarted().consider(), { skipped: "platform-stopped" });
  assert.equal(stopped.calls.light.length, 1);
});

