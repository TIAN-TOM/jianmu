test("时长：本机已知不超过门槛的不读平台；不知道的读，读到的不超过门槛不发；超过的才生成；门槛是 0 时都生成", async () => {
  const known = setup({ known: 5 * 60 });
  assert.deepEqual(await known.auto.consider(), { skipped: "short" });
  assert.equal(known.calls.reads, 0, "知道是短视频就不读字幕");

  const exact = setup({ known: MIN_SEC });
  assert.deepEqual(await exact.auto.consider(), { skipped: "short" }, "正好等于门槛不算超过");

  const unknown = setup({ known: null, read: { durationSec: 5 * 60 } });
  assert.deepEqual(await unknown.auto.consider(), { skipped: "short" });
  assert.equal(unknown.calls.reads, 1, "不知道时长就按超过算，去读");
  assert.deepEqual(unknown.started, [], "读到的时长不够，不发模型请求");

  const noDuration = setup({ known: null, read: { durationSec: 0 } });
  assert.deepEqual(await noDuration.auto.consider(), { started: VIDEO }, "读到了还是不知道时长：按超过算");

  const zero = setup({ minSec: 0, known: 30 });
  assert.deepEqual(await zero.auto.consider(), { started: VIDEO });
});

test("已有概览的不生成；读不成字幕的不生成，十分钟里不再为它读平台", async () => {
  const existing = setup({ overview: true });
  assert.deepEqual(await existing.auto.consider(), { skipped: "has-overview" });
  assert.equal(existing.calls.reads, 0);

  const bare = setup({ read: null });
  assert.deepEqual(await bare.auto.consider(), { skipped: "no-captions" });
  assert.deepEqual(await bare.auto.consider(), { skipped: "unavailable" });
  assert.equal(bare.calls.reads, 1);
  bare.timers.advance(AUTO_RETRY_MS);
  bare.state.read = { durationSec: LONG };
  assert.deepEqual(await bare.auto.consider(), { started: VIDEO });
  assert.deepEqual(bare.ledger().tried, [], "读不成字幕不算试过");
});

test("同时只跑一个；滑动 10 分钟里试满 20 个以后不发，最早的滑出窗口再放行", async () => {
  const busy = setup();
  assert.deepEqual(await busy.auto.consider(), { started: VIDEO });
  busy.state.tabs.set(WINDOW, { id: 4, windowId: WINDOW, url: videoPageUrl(OTHER_ID) });
  assert.deepEqual(await busy.auto.consider(), { skipped: "busy" });

  const sent = Array.from({ length: AUTO_WINDOW_LIMIT }, (_, index) => START - AUTO_WINDOW_MS + 60_000 + index);
  const full = setup({ ledger: { tried: [], sent } });
  assert.deepEqual(await full.auto.consider(), { skipped: "window-full" });
  assert.equal(full.calls.reads, 0, "额度满了不为它取字幕");
  full.timers.advance(60_000);
  assert.deepEqual(await full.auto.consider(), { started: VIDEO });
});

test("尝试在第一个模型请求发出之前才记：那时前台变了就放弃、不记；同时发的几块只核对和记一次", async () => {
  const moved = setup();
  assert.deepEqual(await moved.auto.consider(), { started: VIDEO });
  assert.deepEqual(moved.ledger().tried, [], "开始时不记");
  moved.state.tabs.set(WINDOW, { id: 4, windowId: WINDOW, url: videoPageUrl(SAMPLE_ID) });
  assert.equal(await moved.started[0]?.hooks.beforeSend(false), false, "换了个标签页，哪怕是同一个视频");
  assert.deepEqual(moved.ledger().tried, []);
  // 收尾以后按当时的前台再看一次：它这次在前台，照常开始。
  moved.started[0]?.finish();
  assert.ok(await until(() => moved.started.length === 2));

  const sending = setup();
  await sending.auto.consider();
  const [first] = sending.started;
  assert.ok(first);
  assert.deepEqual(await Promise.all([first.hooks.beforeSend(false), first.hooks.beforeSend(false), first.hooks.beforeSend(false)]), [true, true, true]);
  assert.deepEqual(sending.ledger().tried, [triedKey("overview", VIDEO)]);
  assert.equal(sending.ledger().sent.length, 1);
  first.finish();
  assert.deepEqual(await sending.auto.consider(), { skipped: "tried" }, "发出过的这次会话里不再试");
  assert.equal(sending.started.length, 1);

  for (const change of ["focus", "away", "switch"] as const) {
    const late = setup();
    await late.auto.consider();
    if (change === "focus") late.state.focused = null;
    if (change === "away") late.state.tabs.set(WINDOW, { id: 3, windowId: WINDOW, url: videoPageUrl(OTHER_ID) });
    if (change === "switch") late.state.on = false;
    assert.equal(await late.started[0]?.hooks.beforeSend(false), false, change);
    assert.deepEqual(late.ledger().tried, [], change);
  }
});

