const CURRENT = currentStamp(DATA_CONSENT_TABLE);

type Read = AutoRead<{ readonly durationSec: number } | null>;

interface Setup {
  readonly enabled?: boolean;
  readonly on?: boolean;
  readonly minSec?: number;
  readonly consent?: { readonly version: number; readonly fingerprint: string };
  readonly configReady?: boolean;
  readonly overview?: boolean;
  /** 本机记着的时长。 */
  readonly known?: number | null;
  /** 轻量读取以后知道的时长。 */
  readonly light?: AutoRead<number | null>;
  readonly read?: Read;
  readonly ledger?: unknown;
  readonly launch?: "joined" | "conflict";
  /** 另一个站（经页面读的那种）能不能自动读。 */
  readonly pageReads?: boolean;
}

/** 测试决定自动任务什么时候收尾；没收尾的算在跑。 */
interface Run {
  readonly video: VideoKey;
  readonly hooks: AutoHooks;
  settled: boolean;
  finish(): void;
}

function setup(options: Setup = {}) {
  const timers = manualTimers(START);
  const storage = memoryStorage(options.ledger === undefined ? {} : { [AUTO_LEDGER_KEY]: options.ledger });
  const guard = createClearGuard();
  const started: Run[] = [];
  const paused: (AutoPauseReason | null)[] = [];
  const calls = { windows: 0, listed: 0, known: 0, light: [] as VideoKey[], reads: [] as VideoKey[], sleeps: [] as number[], readTabs: [] as number[] };
  const state = {
    focused: WINDOW as number | null,
    front: FRONT as number | null,
    /** 开着的视频页标签页：编号到地址。 */
    tabs: new Map<number, string>([[FRONT, videoPageUrl(SAMPLE_ID)]]),
    on: options.on ?? true,
    light: options.light === undefined ? (options.known ?? null) : options.light,
    read: (options.read === undefined ? { durationSec: LONG } : options.read) as Read,
    /** 按视频给不同的读取结果。 */
    readOf: new Map<VideoKey, Read>(),
    lightOf: new Map<VideoKey, AutoRead<number | null>>(),
    onRead: null as (() => void) | null,
    /** 等间隔时做的事：比如这时关掉标签页。 */
    onSleep: null as (() => void) | null,
    /** 读一次平台花多久。 */
    readMs: 0,
    /** 这几个视频登记时接上了别处在跑的同一个请求。 */
    joinFor: new Set<VideoKey>(),
  };
  const keyOfRef = (ref: VideoRef): VideoKey => videoKey(ref);
  const deps: AutoGenerateDeps = {
    settings: async () => ({ enabled: options.enabled ?? true, on: state.on, minSec: options.minSec ?? MIN_SEC, consent: options.consent ?? CURRENT }),
    focusedWindow: async () => {
      calls.windows += 1;
      return state.focused;
    },
    activeTab: async (windowId) => (windowId === WINDOW && state.front !== null ? { id: state.front, url: state.tabs.get(state.front) ?? "https://www.bilibili.com/" } : null),
    videoTabs: async () => {
      calls.listed += 1;
      return [...state.tabs].map(([id, url]) => ({ id, url }));
    },
    parseWatchUrl,
    autoReads: (platform) => platform === "bilibili" || options.pageReads === true,
    configReady: async () => options.configReady ?? true,
    running: () => started.filter((run) => !run.settled).length,
    hasOverview: async () => options.overview ?? false,
    knownDuration: async () => {
      calls.known += 1;
      return options.known ?? null;
    },
    lightDuration: async (ref) => {
      calls.light.push(keyOfRef(ref));
      timers.advance(state.readMs);
      return state.lightOf.get(keyOfRef(ref)) ?? state.light;
    },
    readTranscript: async (ref, tabId) => {
      calls.reads.push(keyOfRef(ref));
      calls.readTabs.push(tabId);
      timers.advance(state.readMs);
      state.onRead?.();
      return state.readOf.get(keyOfRef(ref)) ?? state.read;
    },
    sleep: async (ms) => {
      calls.sleeps.push(ms);
      state.onSleep?.();
      timers.advance(ms);
    },
    start: async (_ref, video, hooks): Promise<AutoLaunch> => {
      if (options.launch) return { skipped: options.launch };
      if (state.joinFor.has(video)) return { skipped: "joined" };
      const { promise: done, resolve: finish } = deferred();
      const run: Run = {
        video,
        hooks,
        settled: false,
        finish() {
          run.settled = true;
          finish();
        },
      };
      started.push(run);
      return { done };
    },
    storage,
    guard,
    now: timers.now,
    onPause: (reason) => void paused.push(reason),
    log: { warn() {}, error() {} },
  };
  const auto = createAutoGenerate(deps);
  const ledger = () => parseLedger(storage.data[AUTO_LEDGER_KEY], timers.now());
  /** 让这一个的第一块发出去再收尾，后面的接着排。 */
  const sendAndFinish = async (run: Run | undefined): Promise<void> => {
    assert.ok(run);
    assert.equal(await run.hooks.beforeSend(false), true);
    run.finish();
  };
  /** 后台被回收以后新起的一份：会话存储还在，内存里的都没了。 */
  const restarted = () => createAutoGenerate(deps);
  return { auto, timers, storage, guard, started, paused, calls, state, ledger, sendAndFinish, restarted };
}

