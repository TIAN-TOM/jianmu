export type AutoOutcome = { readonly started: VideoKey } | { readonly skipped: AutoSkip };

/** 交给任务的两个钩子：每次发模型请求之前、请求失败时调。 */
export interface AutoHooks {
  /** false 就不发，这次放弃。vouched：用户自己点的请求接上了这个任务，不再核对前台。 */
  readonly beforeSend: (vouched: boolean) => Promise<boolean>;
  readonly failed: (error: unknown) => void;
}

/** 登记的结果：新起了任务就带着它收尾的那一刻；接上了别处在跑的、撞上别的任务都不算这次开始。 */
export type AutoLaunch = { readonly done: Promise<unknown> } | { readonly skipped: "joined" | "conflict" };

export interface AutoGenerateDeps {
  readonly settings: () => Promise<AutoSettings>;
  readonly consentTable?: NoticeTable<DataConsentKind>;
  /** 现在获得焦点的 Chrome 窗口；焦点不在 Chrome 时是 null。 */
  readonly focusedWindow: () => Promise<number | null>;
  /** 这个窗口的活动标签页，没有时是 null。 */
  readonly activeTab: (windowId: number) => Promise<AutoTab | null>;
  /** 各窗口里开着的、已授权网站视频页的标签页。排队和核对都只按它，两边看到的一致。 */
  readonly videoTabs: () => Promise<readonly AutoTab[]>;
  readonly parseWatchUrl: (url: string) => VideoRef | null;
  /** 这个站的视频能不能自动读字幕。 */
  readonly autoReads: (platform: Platform) => boolean;
  /** 模型配置齐不齐。 */
  readonly configReady: () => Promise<boolean>;
  /** 现在有几个自动发起的任务在跑。 */
  readonly running: () => number;
  /** 这个视频已经有概览记录：基于旧字幕的、不完整的、只用官方总结写过结论的都算。 */
  readonly hasOverview: (video: VideoKey) => Promise<boolean>;
  /** 本机记着的视频时长，不发请求；不知道时是 null。 */
  readonly knownDuration: (ref: VideoRef) => Promise<number | null>;
  /** 做一次轻量读取（不读字幕）再看时长；还不知道是 null。经页面读的站问视频所在的那个标签页。 */
  readonly lightDuration: (ref: VideoRef, tabId: number) => Promise<AutoRead<number | null>>;
  /** 取字幕：缓存没有就向平台读，经页面读的站经视频所在的那个标签页读。读不成字幕时是 null；读成了带回读到的时长。 */
  readonly readTranscript: (ref: VideoRef, tabId: number) => Promise<AutoRead<{ readonly durationSec: number } | null>>;
  readonly sleep: (ms: number) => Promise<void>;
  /** 登记一个来源是自动生成的概览任务并开始。 */
  readonly start: (ref: VideoRef, video: VideoKey, hooks: AutoHooks) => Promise<AutoLaunch>;
  readonly storage: StorageArea;
  readonly guard: ClearGuard;
  readonly now: () => number;
  /** 停下或恢复了：告诉页面。 */
  readonly onPause?: (reason: AutoPauseReason | null) => void;
  readonly log: Log;
}

export interface AutoGenerate {
  /** 把开着的视频标签页过一遍，开始一个或为一个读平台。一轮在跑时再来的排到下一轮，还没开始的几次并成一轮。 */
  consider(): Promise<AutoOutcome>;
  /** 是不是因为额度用完或密钥不对停着。 */
  paused(): Promise<AutoPauseReason | null>;
  /** 用户手动成功生成了一次概览，或者关掉再打开了开关。 */
  resume(): Promise<void>;
}

/** 同时跑几个、滑动窗口里最多几个，都按记下的时间和在跑的个数算。 */
export function quotaOf(sent: readonly number[], running: number, now: number): "busy" | "window-full" | null {
  if (running >= AUTO_CONCURRENCY) return "busy";
  const recent = sent.filter((at) => at > now - AUTO_WINDOW_MS).length;
  return recent >= AUTO_WINDOW_LIMIT ? "window-full" : null;
}

/** 失败的模型请求是不是额度用完、密钥不对或本机服务不收扩展的请求：这几种等多久都不会好，停掉自动生成。 */
export function pauseReasonOf(error: unknown): AutoPauseReason | null {
  const failure = error as { readonly status?: unknown; readonly code?: unknown; readonly quotaExhausted?: unknown } | null;
  if (typeof failure !== "object" || failure === null) return null;
  if (failure.quotaExhausted === true || failure.status === 402) return "quota";
  if (failure.code === "AI_LOCAL_ORIGIN_REJECTED") return "local-origin";
  if (failure.status === 401 || failure.status === 403 || failure.code === "INVALID_AI_KEY" || failure.code === "ANTHROPIC_WORKSPACE_REQUIRED") return "key";
  return null;
}

/** 知道时长、而且不超过门槛：不生成。不知道的按超过算。 */
const isShort = (seconds: number | null, minSec: number): boolean => seconds !== null && seconds > 0 && seconds <= minSec;

interface Trigger {
  readonly tabId: number;
  readonly video: VideoKey;
}

interface Candidate {
  readonly tabId: number;
  readonly ref: VideoRef;
  readonly video: VideoKey;
  /** 获得焦点的窗口里的活动标签页。 */
  readonly front: boolean;
}

export function createAutoGenerate(deps: AutoGenerateDeps): AutoGenerate {
  const { guard, now, log } = deps;
  const table = deps.consentTable ?? DATA_CONSENT_TABLE;
  const ledger = createLedger(deps);
  const queue = createSerialQueue();
  /** 这次醒着时记下的：存储写不进去时也不重试同一个视频。 */
  const triedHere = new Set<string>();
  /** 读不成字幕、没发请求就收尾的视频，到这个时刻之前不再读。会话存储里也记一份，这里是存储写不进去时的兜底。 */
  const unavailable = new Map<VideoKey, number>();
  /** 在后台读不成的视频：这次会话不再读，到了前台再试。 */
  const missedBehind = new Set<VideoKey>();
  /** 已经登记、还没收尾的自动任务的视频：同时跑两个时，下一轮不再挑它。 */
  const inFlight = new Set<VideoKey>();
  /** 读到过的时长：轻量读取只在内存里记最近几个，标签页一多会挤掉，这里自己记着，不为同一个视频再读。 */
  const durations = new Map<VideoKey, number>();
  /** 页面还没准备好的视频：等了几次、到哪个时刻之前不再问。只在内存里记，后台被回收以后从头等。 */
  const pageWaits = new Map<VideoKey, { readonly count: number; readonly until: number }>();
  /** 读平台整批停下，到这个时刻之前不再读。 */
  let stoppedUntil = 0;
  /** 上一次为自动生成读平台的时刻：下一次至少隔开 AUTO_READ_GAP_MS。 */
  let lastRead: number | null = null;
  /** 上面这些记下时的清除代数：清除全部数据以后一起忘掉。 */
  let memorySince = guard.epoch();
  function forgetIfCleared(): void {
    if (!guard.clearedSince(memorySince, "all")) return;
    triedHere.clear();
    unavailable.clear();
    missedBehind.clear();
    durations.clear();
    pageWaits.clear();
    stoppedUntil = 0;
    memorySince = guard.epoch();
  }

  const skip = (reason: AutoSkip): AutoOutcome => ({ skipped: reason });

  // 获得焦点的窗口里的活动标签页：排最前。焦点不在 Chrome 时没有。
  async function frontTabId(): Promise<number | null> {
    const windowId = await deps.focusedWindow();
    if (windowId === null) return null;
    const tab = await deps.activeTab(windowId);
    return typeof tab?.id === "number" ? tab.id : null;
  }

  // 确认和开关都过了才查标签页、读地址。前台的排最前，其余按标签页编号，也就是打开的先后。
  async function candidates(): Promise<readonly Candidate[]> {
    const [front, tabs] = await Promise.all([frontTabId(), deps.videoTabs()]);
    const found: Candidate[] = [];
    const seen = new Set<VideoKey>();
    const ordered = [...tabs].filter((tab): tab is { id: number; url: string } => typeof tab.id === "number" && typeof tab.url === "string");
    ordered.sort((a, b) => (a.id === front ? -1 : b.id === front ? 1 : a.id - b.id));
    for (const tab of ordered) {
      const ref = deps.parseWatchUrl(tab.url);
      const video = ref ? videoKeyOrNull(ref) : null;
      if (!ref || !video || seen.has(video)) continue;
      seen.add(video);
      found.push({ tabId: tab.id, ref, video, front: tab.id === front });
    }
    return found;
  }

  // 读字幕这类步骤是异步的：发请求之前再看一次，那个标签页还开着、地址上还是这个视频。
  async function stillOpen(trigger: Trigger): Promise<boolean> {
    const settings = await deps.settings();
    if (!settings.enabled || !settings.on) return false;
    const tab = (await deps.videoTabs()).find((item) => item.id === trigger.tabId);
    const ref = typeof tab?.url === "string" ? deps.parseWatchUrl(tab.url) : null;
    return ref !== null && videoKeyOrNull(ref) === trigger.video;
  }

  // 确认、开关和含自动发送的同意都还在。
  async function stillOn(): Promise<boolean> {
    const settings = await deps.settings();
    return settings.enabled && settings.on && consentCovers(table, settings.consent, AUTO_SEND_TRIGGER);
  }

  async function pause(reason: AutoPauseReason, since: ClearEpoch | undefined): Promise<void> {
    const changed = await ledger.change(since, (current) => (current.paused ? null : { ...current, paused: { reason, at: now() } }));
    if (changed) deps.onPause?.(reason);
  }

  // 为下一个视频读平台之前隔开一段，从上一个读完算起：一次开几十个标签页时不一口气全去读。
  async function spaced(): Promise<void> {
    const wait = lastRead === null ? 0 : lastRead + AUTO_READ_GAP_MS - now();
    if (wait > 0) await deps.sleep(wait);
  }

  // 读平台定下来的记进会话存储，后台被回收以后不再为同一个视频读。写不进去时内存里那份照样管用。
  function remember(since: ClearEpoch | undefined, mutate: (current: AutoLedger) => AutoLedger): void {
    void ledger.change(since, mutate).catch((error: unknown) => log.error("记自动生成的读取结果失败", errorLabel(error)));
  }

  function rememberDuration(video: VideoKey, seconds: number, since: ClearEpoch | undefined): void {
    if (guard.clearedSince(since, "all")) return;
    durations.set(video, seconds);
    remember(since, (current) => {
      const entries = Object.entries({ ...current.durations, [video]: seconds }).slice(-AUTO_DURATION_LIMIT);
      return { ...current, durations: Object.fromEntries(entries) };
    });
  }

  // 读不成：在前台的冷却一阵，在后台的这次会话不再读，到了前台再试。
  function rememberMissed(candidate: Pick<Candidate, "video" | "front">, since: ClearEpoch | undefined): void {
    if (guard.clearedSince(since, "all")) return;
    const { video, front } = candidate;
    if (front) {
      const until = now() + AUTO_RETRY_MS;
      unavailable.set(video, until);
      remember(since, (current) => ({ ...current, unavailable: { ...current.unavailable, [video]: until } }));
      return;
    }
    missedBehind.add(video);
    remember(since, (current) => ({ ...current, missedBehind: [...new Set([...(current.missedBehind ?? []), video])] }));
  }

  // 整体读不了：整批停下一阵；返回读不懂的，这个视频也记下。
  async function checked<T>(candidate: Candidate, read: () => Promise<AutoRead<T>>, since: ClearEpoch | undefined): Promise<AutoRead<T>> {
    try {
      const result = await read();
      if ((result === "stop" || result === "broken") && !guard.clearedSince(since, "all")) {
        const until = now() + AUTO_RETRY_MS;
        stoppedUntil = until;
        remember(since, (current) => ({ ...current, stoppedUntil: until }));
        if (result === "broken") rememberMissed(candidate, since);
      }
      return result;
    } finally {
      lastRead = now();
    }
  }

  // 页面还没准备好：隔一会儿再看，这期间先看别的视频；等太久就按读不成记下。
  function waitForPage(candidate: Candidate, since: ClearEpoch | undefined): AutoOutcome {
    const count = (pageWaits.get(candidate.video)?.count ?? 0) + 1;
    if (count >= PAGE_WAIT_LIMIT) {
      pageWaits.delete(candidate.video);
      rememberMissed(candidate, since);
      return skip("unavailable");
    }
    pageWaits.set(candidate.video, { count, until: now() + PAGE_WAIT_MS });
    void deps
      .sleep(PAGE_WAIT_MS)
      .then(() => api.consider())
      .catch((error: unknown) => log.error("自动生成判断失败", errorLabel(error)));
    return skip("page-not-ready");
  }

  async function launch(ref: VideoRef, trigger: Trigger & { readonly front: boolean }, since: ClearEpoch | undefined): Promise<AutoOutcome> {
    const key = triedKey(FEATURE, trigger.video);
    let checked: Promise<boolean> | null = null;
    let sent = false;
    let moved = false;
    /** 额度用完或密钥不对：这个任务里还没发的不再发，已经完成的照常保存。 */
    let halted = false;
    const hooks: AutoHooks = {
      // 只在第一次发请求之前核对和记一次，同时发的几块一起等这一次；发出去以后这个任务照常跑完。
      beforeSend(vouched) {
        if (halted) return Promise.resolve(false);
        checked ??= (async () => {
          if (!vouched && !(await stillOpen(trigger))) {
            moved = true;
            return false;
          }
          // 记尝试和核对限额在同一次排队的写里做：两个任务同时到这一步时，滑动窗口只剩一个名额就只放一个。
          // 等的工夫别的任务报了额度用完或密钥不对、整体停了，也不发。用户点的请求接上来的不受这两道限制。
          let refused = false;
          await ledger
            .change(since, (current) => {
              const recent = current.sent.filter((at) => at > now() - AUTO_WINDOW_MS).length;
              if (!vouched && (current.paused || recent >= AUTO_WINDOW_LIMIT)) {
                refused = true;
                return null;
              }
              return { ...current, tried: [...new Set([...current.tried, key])], sent: [...current.sent, now()] };
            })
            .catch((error: unknown) => log.error("记自动生成的尝试失败", errorLabel(error)));
          // 没占上名额：不发、不记尝试，也不算读不成，等窗口滑出去再排。
          if (refused) {
            moved = true;
            return false;
          }
          sent = true;
          if (!guard.clearedSince(since, "all")) triedHere.add(key);
          // 写记录要等存储：这期间关掉了开关、撤回了同意或确认失效，就不发。记录照留，这次会话不再为它试。
          return vouched || (await stillOn());
        })();
        return checked;
      },
      failed(error) {
        const reason = pauseReasonOf(error);
        if (!reason) return;
        halted = true;
        void pause(reason, since).catch((failure: unknown) => log.error("停掉自动生成失败", errorLabel(failure)));
      },
    };
    const launched = await deps.start(ref, trigger.video, hooks);
    if ("skipped" in launched) return skip(launched.skipped);
    inFlight.add(trigger.video);
    void launched.done
      .catch(() => undefined)
      .then(() => {
        inFlight.delete(trigger.video);
        // 没发出请求就收了尾、又不是因为关了标签页或换了视频：一阵子里不再为它读平台，免得同一个视频一遍遍读。
        if (!sent && !moved) rememberMissed(trigger, since);
        // 接着排下一个。
        return api.consider();
      })
      .catch((error: unknown) => log.error("自动生成判断失败", errorLabel(error)));
    return { started: trigger.video };
  }

  /** 只看本机记着的就能定下来的：不读平台。 */
  async function settledLocally(candidate: Candidate, record: AutoLedger, minSec: number): Promise<AutoSkip | null> {
    const { ref, video, front } = candidate;
    if (!deps.autoReads(ref.platform)) return "site-unsupported";
    if (inFlight.has(video)) return "joined";
    const key = triedKey(FEATURE, video);
    if (record.tried.includes(key) || triedHere.has(key)) return "tried";
    if (Math.max(unavailable.get(video) ?? 0, record.unavailable?.[video] ?? 0) > now()) return "unavailable";
    if (!front && (missedBehind.has(video) || record.missedBehind?.includes(video))) return "unavailable";
    if ((pageWaits.get(video)?.until ?? 0) > now()) return "page-not-ready";
    if (await deps.hasOverview(video)) return "has-overview";
    const known = durations.get(video) ?? record.durations?.[video] ?? (await deps.knownDuration(ref));
    if (known !== null) durations.set(video, known);
    return isShort(known, minSec) ? "short" : null;
  }

  /** 为一个视频读平台：时长不知道先轻量读取，再读字幕，按读到的再判断；都过了就登记任务。 */
  async function tryOne(candidate: Candidate, settings: AutoSettings, since: ClearEpoch | undefined): Promise<AutoOutcome> {
    const { ref, video, tabId, front } = candidate;
    const trigger: Trigger & { readonly front: boolean } = { tabId, video, front };
    await spaced();
    // 等间隔的工夫标签页可能关了、换了视频，别的任务也可能报了额度用完或密钥不对：读平台之前再看一次。
    if ((await ledger.read()).paused) return skip("paused");
    if (!(await stillOpen(trigger))) return skip("moved");
    if (!durations.has(video)) {
      const seconds = await checked(candidate, () => deps.lightDuration(ref, tabId), since);
      if (seconds === "stop" || seconds === "broken") return skip("platform-stopped");
      if (seconds === "later") return waitForPage(candidate, since);
      if (seconds !== null) rememberDuration(video, seconds, since);
      if (isShort(seconds, settings.minSec)) return skip("short");
    }
    const read = await checked(candidate, () => deps.readTranscript(ref, tabId), since);
    if (read === "stop" || read === "broken") return skip("platform-stopped");
    if (read === "later") return waitForPage(candidate, since);
    pageWaits.delete(video);
    if (!read) {
      rememberMissed(candidate, since);
      return skip("no-captions");
    }
    rememberDuration(video, read.durationSec, since);
    if (isShort(read.durationSec, settings.minSec)) return skip("short");
    if (!(await stillOpen(trigger))) return skip("moved");
    return launch(ref, trigger, since);
  }

  async function evaluate(): Promise<AutoOutcome> {
    forgetIfCleared();
    const since = guard.epoch();
    const settings = await deps.settings();
    if (!settings.enabled) return skip("not-enabled");
    if (!settings.on) return skip("switch-off");
    const list = await candidates();
    if (list.length === 0) return skip("not-video");
    if (!list.some((candidate) => deps.autoReads(candidate.ref.platform))) return skip("site-unsupported");
    if (!consentCovers(table, settings.consent, AUTO_SEND_TRIGGER)) return skip("no-consent");
    if (!(await deps.configReady())) return skip("no-config");
    const record = await ledger.read();
    if (record.paused) return skip("paused");
    const over = quotaOf(record.sent, deps.running(), now());
    if (over) return skip(over);
    if (Math.max(stoppedUntil, record.stoppedUntil ?? 0) > now()) return skip("platform-stopped");
    let first: AutoSkip | null = null;
    for (const candidate of list) {
      const settled = await settledLocally(candidate, record, settings.minSec);
      if (settled) {
        first ??= settled;
        continue;
      }
      const outcome = await tryOne(candidate, settings, since);
      // 接上了别处在跑的同一个请求、撞上别的任务、页面还没准备好：这个视频这会儿定了，接着看下一个。
      if ("skipped" in outcome && (outcome.skipped === "joined" || outcome.skipped === "conflict" || outcome.skipped === "page-not-ready")) {
        first ??= outcome.skipped;
        continue;
      }
      // 为这个视频读过平台或开始了一个：这一轮到此为止，排到下一轮接着看（还有空位就再开始一个），期间来的事件（比如换了前台）先处理。
      if ("started" in outcome || outcome.skipped !== "platform-stopped") void api.consider().catch((error: unknown) => log.error("自动生成判断失败", errorLabel(error)));
      return outcome;
    }
    return skip(first ?? "not-video");
  }

  /** 排着还没开始的那一轮：这期间再来的事件并进它，一次加载触发的几个事件不排出几轮。 */
  let waiting: Promise<AutoOutcome> | null = null;
  const api: AutoGenerate = {
    consider() {
      waiting ??= queue(() => {
        waiting = null;
        return evaluate();
      });
      return waiting;
    },
    async paused() {
      return (await ledger.read()).paused?.reason ?? null;
    },
    async resume() {
      const changed = await ledger.change(guard.epoch(), (current) => {
        if (!current.paused) return null;
        const { paused: _paused, ...rest } = current;
        return rest;
      });
      if (changed) deps.onPause?.(null);
    },
  };
  return api;
}
