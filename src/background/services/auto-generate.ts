// 打开 B 站视频就生成概览和翻译的闸门（骨架）。后台看到获得焦点的窗口里的活动视频标签页时问一次：
// 先过四道共用的闸门（站点、同意、配置、额度），再分别判断概览和翻译。这一步还没有开关，数据同意里也没有自动发送，
// 后台不注册标签页和窗口事件，生产里恒不触发；调模型前再核对焦点、额度用完时停掉自动生成随开关一起接上。
// 确认启用之前、开关关着时不读标签页地址。只认 B 站：YouTube 视频不取字幕、不记尝试。
// 尝试记录在模型请求真正发出时才记，发出后失败也算试过，不静默重试；同时只跑一个，滑动 10 分钟最多 20 个。
import type { ClearEpoch, ClearGuard } from "../../core/clear-guard.ts";
import { createSerialQueue } from "../../core/concurrency.ts";
import { consentCovers, DATA_CONSENT_TABLE, type DataConsentKind, type NoticeTable, type StoredStamp } from "../../core/consent.ts";
import { videoKey, type VideoKey, type VideoRef } from "../../core/video-ref.ts";
import type { StorageArea } from "../../platform/storage.ts";
import { AUTO_LEDGER_KEY } from "../../shared/names.ts";
import type { TranscriptReply } from "../../shared/messages/transcript.ts";
import { errorLabel, type Log } from "../log.ts";
import { targetOf } from "./translate.ts";

export const AUTO_WINDOW_MS = 10 * 60_000;
export const AUTO_WINDOW_LIMIT = 20;
export const AUTO_CONCURRENCY = 1;
/** 数据同意里「打开视频就自动发送」那一条。说明表里有了它、用户同意了那一版，自动生成才算得到同意。 */
export const AUTO_SEND_TRIGGER = { kind: "trigger", id: "auto-on-open" } as const satisfies { kind: DataConsentKind; id: string };
/** 尝试记录最多留多少条：一次浏览器会话里够用，再多就丢最早的。 */
const LEDGER_MAX = 500;

export type AutoFeature = "overview" | "translate";

export interface AutoAttempt {
  readonly feature: AutoFeature;
  readonly video: VideoKey;
  readonly at: number;
}

/** 后台看到的标签页。地址要过了确认和开关两道才读。 */
export interface AutoTab {
  readonly id?: number;
  readonly windowId?: number;
  readonly active?: boolean;
  readonly url?: string;
}

export type AutoSkip =
  | "not-focused"
  | "not-enabled"
  | "switch-off"
  | "not-video"
  | "site-unsupported"
  | "no-consent"
  | "no-config"
  | "busy"
  | "window-full"
  | "nothing-to-do";

export type AutoOutcome = { readonly started: AutoFeature; readonly video: VideoKey } | { readonly skipped: AutoSkip };

export interface AutoGenerateDeps {
  /** 现在获得焦点的 Chrome 窗口；焦点不在 Chrome 时是 null。 */
  readonly focusedWindow: () => Promise<number | null>;
  /** 首次启用确认算不算数。 */
  readonly enabled: () => Promise<boolean>;
  /** 自动生成的开关。 */
  readonly switchOn: () => Promise<boolean>;
  readonly parseWatchUrl: (url: string) => VideoRef | null;
  /** 存着的数据同意。 */
  readonly consent: () => Promise<StoredStamp>;
  readonly consentTable?: NoticeTable<DataConsentKind>;
  /** 模型配置齐不齐。 */
  readonly configReady: () => Promise<boolean>;
  /** 现在有几个自动发起的任务在跑。 */
  readonly running: () => number;
  /** 取字幕：缓存没有就向平台读。读不成字幕时带回来的官方总结也算材料。 */
  readonly transcript: (ref: VideoRef) => Promise<TranscriptReply>;
  readonly hasOverview: (video: VideoKey) => Promise<boolean>;
  /** 这一版字幕有没有译成这种语言的记录。 */
  readonly hasTranslation: (reply: Extract<TranscriptReply, { ok: true }>["value"], target: "zh" | "en") => Promise<boolean>;
  /** 发起一个来源是自动生成的任务。onSend 要在每次真正发出模型请求之前调。 */
  readonly start: (feature: AutoFeature, ref: VideoRef, hooks: { readonly onSend: () => void }) => void;
  readonly storage: StorageArea;
  readonly guard: ClearGuard;
  readonly now: () => number;
  readonly log: Log;
}

export interface AutoGenerate {
  consider(tab: AutoTab): Promise<AutoOutcome>;
}

/** 尝试记录是纯数据：同时只跑一个、滑动窗口里最多几个，都按它和在跑的个数算。 */
export function quotaOf(attempts: readonly AutoAttempt[], running: number, now: number): AutoSkip | null {
  if (running >= AUTO_CONCURRENCY) return "busy";
  const recent = attempts.filter((attempt) => attempt.at > now - AUTO_WINDOW_MS).length;
  return recent >= AUTO_WINDOW_LIMIT ? "window-full" : null;
}

const isAttempt = (value: unknown): value is AutoAttempt => {
  const item = value as Partial<AutoAttempt> | null;
  return typeof item === "object" && item !== null && (item.feature === "overview" || item.feature === "translate") && typeof item.video === "string" && Number.isFinite(item.at);
};

/** 尝试记录存在会话存储里：浏览器重开就清空，清除全部数据时也删。 */
function createLedger({ storage, guard, log }: Pick<AutoGenerateDeps, "storage" | "guard" | "log">) {
  const queue = createSerialQueue();
  async function read(): Promise<AutoAttempt[]> {
    try {
      const stored = (await storage.get(AUTO_LEDGER_KEY))[AUTO_LEDGER_KEY] as { attempts?: unknown } | undefined;
      return Array.isArray(stored?.attempts) ? stored.attempts.filter(isAttempt) : [];
    } catch (error) {
      log.warn("读自动生成的尝试记录失败", errorLabel(error));
      return [];
    }
  }
  return {
    read,
    /** since：触发时记下的清除代数。 */
    record(attempt: AutoAttempt, since: ClearEpoch | undefined): Promise<void> {
      return queue(() =>
        guard.track(async () => {
          // 触发以后清除过全部数据：那是清除之前触发的任务，不把记录写回去。
          if (guard.clearedSince(since, "all")) return;
          const attempts = [...(await read()), attempt].slice(-LEDGER_MAX);
          await storage.set({ [AUTO_LEDGER_KEY]: { attempts } });
        }),
      );
    },
  };
}

// 有字幕，或者读不成字幕但有官方总结：两样都没有不为它发请求。
const hasMaterial = (reply: TranscriptReply): boolean =>
  reply.ok || (reply.official?.status === "ok" && (reply.official.summary.trim() !== "" || reply.official.outline.length > 0));

export function createAutoGenerate(deps: AutoGenerateDeps): AutoGenerate {
  const ledger = createLedger(deps);
  const table = deps.consentTable ?? DATA_CONSENT_TABLE;

  // 已经试过的不再试：同一个视频同一项功能，这次浏览器会话里只试一次。
  async function pick(ref: VideoRef, video: VideoKey, attempts: readonly AutoAttempt[]): Promise<AutoFeature | null> {
    const tried = (feature: AutoFeature): boolean => attempts.some((attempt) => attempt.feature === feature && attempt.video === video);
    const wantsOverview = !tried("overview") && !(await deps.hasOverview(video));
    if (!wantsOverview && tried("translate")) return null;
    const reply = await deps.transcript(ref);
    if (wantsOverview && hasMaterial(reply)) return "overview";
    // 外文视频、这一版字幕还没有中文译文：已有概览的照样翻译。
    if (!tried("translate") && reply.ok && targetOf(reply.value.transcript.ref.lang) === "zh" && !(await deps.hasTranslation(reply.value, "zh"))) return "translate";
    return null;
  }

  return {
    async consider(tab) {
      const since = deps.guard.epoch();
      // 焦点和确认、开关都不用看地址：没过这几道不读它。
      const focused = await deps.focusedWindow();
      if (focused === null || tab.active !== true || tab.windowId !== focused) return { skipped: "not-focused" };
      if (!(await deps.enabled())) return { skipped: "not-enabled" };
      if (!(await deps.switchOn())) return { skipped: "switch-off" };
      const ref = typeof tab.url === "string" ? deps.parseWatchUrl(tab.url) : null;
      if (!ref) return { skipped: "not-video" };
      if (ref.platform !== "bilibili") return { skipped: "site-unsupported" };
      if (!consentCovers(table, await deps.consent(), AUTO_SEND_TRIGGER)) return { skipped: "no-consent" };
      if (!(await deps.configReady())) return { skipped: "no-config" };
      const attempts = await ledger.read();
      const over = quotaOf(attempts, deps.running(), deps.now());
      if (over) return { skipped: over };
      const video = videoKey(ref);
      const feature = await pick(ref, video, attempts);
      if (!feature) return { skipped: "nothing-to-do" };
      let recorded = false;
      deps.start(feature, ref, {
        onSend() {
          if (recorded) return;
          recorded = true;
          void ledger.record({ feature, video, at: deps.now() }, since).catch((error: unknown) => deps.log.error("记自动生成的尝试失败", errorLabel(error)));
        },
      });
      return { started: feature, video };
    },
  };
}
