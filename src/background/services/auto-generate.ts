export const AUTO_WINDOW_LIMIT = 40;
export const AUTO_CONCURRENCY = 2;
/** 读不成字幕、没发请求就收了尾的视频，这么久里不再为它读平台；读平台整批停下时也停这么久。 */
export const AUTO_RETRY_MS = AUTO_WINDOW_MS;
/** 为下一个视频读平台之前至少隔这么久，和本窗口全部生成一样。 */
export const AUTO_READ_GAP_MS = OFFICIAL_INTERVAL_MS;
/** 经页面读的站页面还没准备好时，隔这么久再看一次。 */
export const PAGE_WAIT_MS = 5000;
/** 同一个视频的页面最多等这么多次（约两分钟，够放完片头广告），还不行就按读不成记下。 */
export const PAGE_WAIT_LIMIT = 24;
/** 数据同意里「打开视频就自动发送，后台打开的也算」那一条。说明表里有了它、用户同意了那一版，自动生成才算得到同意。 */
export const AUTO_SEND_TRIGGER = { kind: "trigger", id: "auto-on-open-tabs" } as const satisfies { kind: DataConsentKind; id: string };


/** 后台看到的标签页。地址要过了确认和开关两道才读。 */
export interface AutoTab {
  readonly id?: number;
  readonly url?: string;
}

/**
 * 读平台的结果：stop 是这会儿整体读不了（限流、人机验证、没登录），整批停下；broken 是返回读不懂，整批停下，这个视频也记下不再读；
 * later 是要经页面读的站那个页面还没准备好（还在加载、在播广告），过一会儿再试，不算读不成。
 */
export type AutoRead<T> = T | "stop" | "broken" | "later";


/** 一次判断要用的设置，一次读出来。 */
