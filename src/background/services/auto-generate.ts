// 打开 B 站视频就生成概览和一句话结论，不自动翻译。标签页激活、地址变了、窗口焦点变了，都按那一刻获得焦点的窗口里的
// 活动标签页判断一次，一次只判断一个。确认启用和开关两道之前不碰标签页；只认 B 站，YouTube 不取字幕、不记尝试。
// 时长门槛先按本机已经知道的判断，不知道就当超过，读完字幕再按读到的判断一次；发第一个模型请求之前再核对焦点、
// 活动标签页和视频，变了就放弃、不记尝试。尝试在那时才记，试过的这次浏览器会话里不再试；同时只跑一个，滑动 10 分钟最多 20 个。
// 模型服务说额度用完或密钥不对时停掉，手动成功生成一次概览或重开开关后恢复。
import type { ClearEpoch, ClearGuard } from "../../core/clear-guard.ts";
import { createSerialQueue } from "../../core/concurrency.ts";
import { consentCovers, DATA_CONSENT_TABLE, type DataConsentKind, type NoticeTable, type StoredStamp } from "../../core/consent.ts";
import { videoKey, type VideoKey, type VideoRef } from "../../core/video-ref.ts";
import type { StorageArea } from "../../platform/storage.ts";
import type { AutoPauseReason } from "../../shared/messages/ai.ts";
import { AUTO_LEDGER_KEY } from "../../shared/names.ts";
import { errorLabel, type Log } from "../log.ts";

export type { AutoPauseReason };

export const AUTO_WINDOW_MS = 10 * 60_000;
export const AUTO_WINDOW_LIMIT = 20;
export const AUTO_CONCURRENCY = 1;
/** 读不成字幕、没发请求就收了尾的视频，这么久里不再为它读平台。 */
export const AUTO_RETRY_MS = AUTO_WINDOW_MS;
/** 数据同意里「打开视频就自动发送」那一条。说明表里有了它、用户同意了那一版，自动生成才算得到同意。 */
export const AUTO_SEND_TRIGGER = { kind: "trigger", id: "auto-on-open" } as const satisfies { kind: DataConsentKind; id: string };

/** 只自动生成概览（连同一句话结论）。尝试记录按「功能:视频键」记，以后加功能时各记各的。 */
export type AutoFeature = "overview";
const FEATURE: AutoFeature = "overview";

/** 后台看到的标签页。地址要过了确认和开关两道才读。 */
export interface AutoTab {
  readonly id?: number;
  readonly windowId?: number;
  readonly url?: string;
}

/** 一次判断要用的设置，一次读出来。 */
export interface AutoSettings {
  /** 首次启用确认算不算数。 */
  readonly enabled: boolean;
  /** 打开就出结论的开关。 */
  readonly on: boolean;
  /** 超过这么多秒的视频才生成。 */
  readonly minSec: number;
  /** 存着的数据同意。 */
  readonly consent: StoredStamp;
}

export type AutoSkip =
  | "not-enabled"
  | "switch-off"
  | "not-focused"
  | "not-video"
  | "site-unsupported"
  | "no-consent"
  | "no-config"
  | "paused"
  | "busy"
  | "window-full"
  | "tried"
  | "unavailable"
  | "has-overview"
  | "short"
  | "no-captions"
  | "moved"
  | "joined"
  | "conflict";

export type AutoOutcome = { readonly started: VideoKey } | { readonly skipped: AutoSkip };

/** 交给任务的两个钩子：每次发模型请求之前、请求失败时调。 */
export interface AutoHooks {
  /** false 就不发，这次放弃。vouched：用户自己点的请求接上了这个任务，不再核对前台。 */
  readonly beforeSend: (vouched: boolean) => Promise<boolean>;
  readonly failed: (error: unknown) => void;
}

/** 登记的结果：新起了任务就带着它收尾的那一刻；接上了别处在跑的、撞上别的任务都不算这次开始。 */
export type AutoLaunch = { readonly done: Promise<unknown> } | { readonly skipped: "joined" | "conflict" };

export interface AutoGenerateDeps {
  readonly settings: () => Promise<AutoSettings>;
  readonly consentTable?: NoticeTable<DataConsentKind>;
  /** 现在获得焦点的 Chrome 窗口；焦点不在 Chrome 时是 null。 */
  readonly focusedWindow: () => Promise<number | null>;
  /** 这个窗口的活动标签页，没有时是 null。 */
  readonly activeTab: (windowId: number) => Promise<AutoTab | null>;
  readonly parseWatchUrl: (url: string) => VideoRef | null;
  /** 模型配置齐不齐。 */
  readonly configReady: () => Promise<boolean>;
  /** 现在有几个自动发起的任务在跑。 */
  readonly running: () => number;
  /** 这个视频已经有概览（章节或金句），基于旧字幕的、不完整的都算。 */
  readonly hasOverview: (video: VideoKey) => Promise<boolean>;
  /** 后台自己读到过的时长，只看本机记着的，不发请求；不知道时是 null。 */
  readonly knownDuration: (ref: VideoRef) => Promise<number | null>;
  /** 取字幕：缓存没有就向平台读。读不成字幕时是 null；读成了带回读到的时长。 */
  readonly readTranscript: (ref: VideoRef) => Promise<{ readonly durationSec: number } | null>;
  /** 登记一个来源是自动生成的概览任务并开始。 */
  readonly start: (ref: VideoRef, video: VideoKey, hooks: AutoHooks) => Promise<AutoLaunch>;
  readonly storage: StorageArea;
  readonly guard: ClearGuard;
  readonly now: () => number;
  /** 停下或恢复了：告诉页面。 */
  readonly onPause?: (reason: AutoPauseReason | null) => void;
  readonly log: Log;
}

export interface AutoGenerate {
  /** 按那一刻获得焦点的窗口里的活动标签页判断一次。几次一起来时排队，一个判断完再判断下一个。 */
  consider(): Promise<AutoOutcome>;
  /** 是不是因为额度用完或密钥不对停着。 */
  paused(): Promise<AutoPauseReason | null>;
  /** 用户手动成功生成了一次概览，或者关掉再打开了开关。 */
  resume(): Promise<void>;
}

/** 尝试记录：试过的整个浏览器会话都留着，计数只留最近 10 分钟的。 */
export interface AutoLedger {
  readonly tried: readonly string[];
  readonly sent: readonly number[];
  readonly paused?: { readonly reason: AutoPauseReason; readonly at: number };
}

export const triedKey = (feature: AutoFeature, video: VideoKey): string => `${feature}:${video}`;

/** 同时只跑一个、滑动窗口里最多几个，都按记下的时间和在跑的个数算。 */
export function quotaOf(sent: readonly number[], running: number, now: number): "busy" | "window-full" | null {
  if (running >= AUTO_CONCURRENCY) return "busy";
  const recent = sent.filter((at) => at > now - AUTO_WINDOW_MS).length;
  return recent >= AUTO_WINDOW_LIMIT ? "window-full" : null;
}

/** 失败的模型请求是不是额度用完或密钥不对：这两种等多久都不会好，停掉自动生成。 */
export function pauseReasonOf(error: unknown): AutoPauseReason | null {
  const failure = error as { readonly status?: unknown; readonly code?: unknown; readonly quotaExhausted?: unknown } | null;
  if (typeof failure !== "object" || failure === null) return null;
  if (failure.quotaExhausted === true || failure.status === 402) return "quota";
  if (failure.status === 401 || failure.status === 403 || failure.code === "INVALID_AI_KEY" || failure.code === "ANTHROPIC_WORKSPACE_REQUIRED") return "key";
  return null;
}

const isPlainObject = (value: unknown): value is Readonly<Record<string, unknown>> => typeof value === "object" && value !== null && !Array.isArray(value);
const isTime = (value: unknown): value is number => typeof value === "number" && Number.isFinite(value);
const isPauseReason = (value: unknown): value is AutoPauseReason => value === "quota" || value === "key";

/** 存储里的记录形状不可信，逐项核对。早先只记 attempts 的写法照样认概览那种，别的（翻译）忽略。 */
export function parseLedger(stored: unknown, now: number): AutoLedger {
  const record = isPlainObject(stored) ? stored : {};
  const tried = new Set<string>(Array.isArray(record.tried) ? record.tried.filter((item): item is string => typeof item === "string") : []);
  const sent = Array.isArray(record.sent) ? record.sent.filter(isTime) : [];
  for (const item of Array.isArray(record.attempts) ? record.attempts : []) {
    if (!isPlainObject(item) || item.feature !== FEATURE || typeof item.video !== "string" || !isTime(item.at)) continue;
    tried.add(triedKey(FEATURE, item.video as VideoKey));
    sent.push(item.at);
  }
  const paused = isPlainObject(record.paused) && isPauseReason(record.paused.reason) && isTime(record.paused.at) ? { reason: record.paused.reason, at: record.paused.at } : undefined;
  return { tried: [...tried], sent: sent.filter((at) => at > now - AUTO_WINDOW_MS).sort((a, b) => a - b), ...(paused ? { paused } : {}) };
}

/** 尝试记录存在会话存储里：浏览器重开就清空，清除全部数据时也删。写排成一条队，清除之后不把之前的写回去。 */
function createLedger({ storage, guard, now, log }: Pick<AutoGenerateDeps, "storage" | "guard" | "now" | "log">) {
  const queue = createSerialQueue();
  async function read(): Promise<AutoLedger> {
    try {
      return parseLedger((await storage.get(AUTO_LEDGER_KEY))[AUTO_LEDGER_KEY], now());
    } catch (error) {
      log.warn("读自动生成的尝试记录失败", errorLabel(error));
      return parseLedger(undefined, now());
    }
  }
  function change(since: ClearEpoch | undefined, mutate: (ledger: AutoLedger) => AutoLedger | null): Promise<boolean> {
    return queue(() =>
      guard.track(async () => {
        if (guard.clearedSince(since, "all")) return false;
        const next = mutate(await read());
        if (!next) return false;
        await storage.set({ [AUTO_LEDGER_KEY]: next });
        return true;
      }),
    );
  }
  return { read, change };
}

const keyOf = (ref: VideoRef): VideoKey | null => {
  try {
    return videoKey(ref);
  } catch {
    return null;
  }
};

/** 知道时长、而且不超过门槛：不生成。不知道的按超过算。 */
const isShort = (seconds: number | null, minSec: number): boolean => seconds !== null && seconds > 0 && seconds <= minSec;

interface Trigger {
  readonly windowId: number;
  readonly tabId: number;
  readonly video: VideoKey;
}

interface Front {
  readonly settings: AutoSettings;
  readonly windowId: number;
  readonly tabId: number;
  readonly ref: VideoRef;
}

export function createAutoGenerate(deps: AutoGenerateDeps): AutoGenerate {
  const { guard, now, log } = deps;
  const table = deps.consentTable ?? DATA_CONSENT_TABLE;
  const ledger = createLedger(deps);
  const queue = createSerialQueue();
  /** 这次醒着时记下的：存储写不进去时也不重试同一个视频。 */
  const triedHere = new Set<string>();
  /** 读不成字幕、没发请求就收尾的视频，到这个时刻之前不再读。 */
  const unavailable = new Map<VideoKey, number>();

  const skip = (reason: AutoSkip): AutoOutcome => ({ skipped: reason });

  // 确认和开关都过了才问窗口和标签页，才读地址。
  async function inFront(): Promise<Front | AutoSkip> {
    const settings = await deps.settings();
    if (!settings.enabled) return "not-enabled";
    if (!settings.on) return "switch-off";
    const windowId = await deps.focusedWindow();
    if (windowId === null) return "not-focused";
    const tab = await deps.activeTab(windowId);
    if (!tab || typeof tab.id !== "number" || typeof tab.url !== "string") return "not-video";
    const ref = deps.parseWatchUrl(tab.url);
    return ref ? { settings, windowId, tabId: tab.id, ref } : "not-video";
  }

  // 读字幕这类步骤是异步的：发请求之前再看一次，还是同一个窗口获得焦点、同一个标签页在前台、地址上还是这个视频。
  async function stillInFront(trigger: Trigger): Promise<boolean> {
    const front = await inFront();
    return typeof front !== "string" && front.windowId === trigger.windowId && front.tabId === trigger.tabId && keyOf(front.ref) === trigger.video;
  }

  async function pause(reason: AutoPauseReason, since: ClearEpoch | undefined): Promise<void> {
    const changed = await ledger.change(since, (current) => (current.paused ? null : { ...current, paused: { reason, at: now() } }));
    if (changed) deps.onPause?.(reason);
  }

  async function launch(ref: VideoRef, trigger: Trigger, since: ClearEpoch | undefined): Promise<AutoOutcome> {
    const key = triedKey(FEATURE, trigger.video);
    let checked: Promise<boolean> | null = null;
    let sent = false;
    let moved = false;
    const hooks: AutoHooks = {
      // 只在第一次发请求之前核对和记一次，同时发的几块一起等这一次；发出去以后这个任务照常跑完。
      beforeSend(vouched) {
        checked ??= (async () => {
          if (!vouched && !(await stillInFront(trigger))) {
            moved = true;
            return false;
          }
          sent = true;
          triedHere.add(key);
          await ledger
            .change(since, (current) => ({ ...current, tried: [...new Set([...current.tried, key])], sent: [...current.sent, now()] }))
            .catch((error: unknown) => log.error("记自动生成的尝试失败", errorLabel(error)));
          return true;
        })();
        return checked;
      },
      failed(error) {
        const reason = pauseReasonOf(error);
        if (reason) void pause(reason, since).catch((failure: unknown) => log.error("停掉自动生成失败", errorLabel(failure)));
      },
    };
    const launched = await deps.start(ref, trigger.video, hooks);
    if ("skipped" in launched) return skip(launched.skipped);
    void launched.done
      .catch(() => undefined)
      .then(() => {
        // 没发出请求就收了尾、又不是因为换了前台：一阵子里不再为它读平台，免得同一个视频一遍遍读。
        if (!sent && !moved) unavailable.set(trigger.video, now() + AUTO_RETRY_MS);
        // 它在跑时别的视频可能被跳过了：按现在的前台再看一次。
        return api.consider();
      })
      .catch((error: unknown) => log.error("自动生成判断失败", errorLabel(error)));
    return { started: trigger.video };
  }

  async function evaluate(): Promise<AutoOutcome> {
    const since = guard.epoch();
    const front = await inFront();
    if (typeof front === "string") return skip(front);
    const { settings, windowId, tabId, ref } = front;
    if (ref.platform !== "bilibili") return skip("site-unsupported");
    const video = keyOf(ref);
    if (!video) return skip("not-video");
    if (!consentCovers(table, settings.consent, AUTO_SEND_TRIGGER)) return skip("no-consent");
    if (!(await deps.configReady())) return skip("no-config");
    const record = await ledger.read();
    if (record.paused) return skip("paused");
    const over = quotaOf(record.sent, deps.running(), now());
    if (over) return skip(over);
    const key = triedKey(FEATURE, video);
    if (record.tried.includes(key) || triedHere.has(key)) return skip("tried");
    if ((unavailable.get(video) ?? 0) > now()) return skip("unavailable");
    if (await deps.hasOverview(video)) return skip("has-overview");
    if (isShort(await deps.knownDuration(ref), settings.minSec)) return skip("short");
    const read = await deps.readTranscript(ref);
    if (!read) {
      unavailable.set(video, now() + AUTO_RETRY_MS);
      return skip("no-captions");
    }
    if (isShort(read.durationSec, settings.minSec)) return skip("short");
    const trigger: Trigger = { windowId, tabId, video };
    if (!(await stillInFront(trigger))) return skip("moved");
    return launch(ref, trigger, since);
  }

  const api: AutoGenerate = {
    consider: () => queue(evaluate),
    async paused() {
      return (await ledger.read()).paused?.reason ?? null;
    },
    async resume() {
      const changed = await ledger.change(guard.epoch(), (current) => {
        if (!current.paused) return null;
        const { paused: _paused, ...rest } = current;
        return rest;
      });
      if (changed) deps.onPause?.(null);
    },
  };
  return api;
}
