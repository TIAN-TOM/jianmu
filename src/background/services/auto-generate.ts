// 打开视频就生成概览和一句话结论，后台打开的标签页也排进来，不自动翻译。标签页有变化、窗口焦点变了，都把已授权网站上
// 开着的视频标签页过一遍：获得焦点的窗口里的活动标签页排最前，其余按打开的先后。确认启用和开关两道之前不碰标签页；
// 只认能自动读的站（B 站；YouTube 要经页面读，能替用户点开文字稿面板的构建里才算）。一轮最多为一个视频读平台，读完排到下一轮，
// 两次读之间隔开；被限流、要人机验证、没登录或读不懂时整批停下一阵。经页面读的站页面还没准备好（还在加载、在播广告）时
// 隔一会儿再看，等太久才算读不成。时长门槛先按本机记着的判断，不知道就先做一次轻量读取（不读字幕），还不知道就当超过，
// 读完字幕再按读到的判断一次；发第一个模型请求之前再核对标签页还开着、还是这个视频，变了就放弃、不记尝试。尝试在那时才记，
// 试过的这次浏览器会话里不再试；同时最多跑两个，滑动 10 分钟最多 40 个。
// 模型服务说额度用完或密钥不对时停掉，手动成功生成一次概览或重开开关后恢复。
